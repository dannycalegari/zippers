/*  chz.cc  --  complex hyperbolic zipper, stage 1: exact group arithmetic and the
    block-filling search.

    THE GROUP.  Pi = pi_1 of the Cartwright-Steger surface X = Pi\B^2, generated by the
    elements a1, a2, a3 of Cartwright-Koziarz-Yeung (arXiv:1412.4137, Theorem 2): a
    torsion-free subgroup of index 864 in the arithmetic lattice Gamma-bar = <u,v,b> of
    PU(2,1).  In CKY's "primed" coordinates every element of Gamma-bar is a 3x3 matrix over
    Z[zeta], zeta = exp(pi i/6), unitary for the Hermitian form F', defined modulo the scalars
    zeta^k.  So all group arithmetic here is EXACT.  An element is stored as its matrix,
    normalised by the power of zeta that makes the (3,3) entry lexicographically least.  Pi
    acts freely on the ball, so an element is determined by its third column, the image of
    the origin o = [0:0:1] (the fixed point of the order-288 subgroup <u,v>); that column is
    the hash key.  d(o, g o) = 2 acosh |g_33| (holomorphic curvature -1).

    THE HOMOMORPHISM.  H_1(Pi) = Z^2 by f(a1) = (1,3), f(a2) = (-2,1), f(a3) = (-1,-1), and
    phi = first coordinate of f.  Every element carries its f-value, and f is checked to be
    well defined whenever an element is reached by two different paths.

    THE BLOCK-FILLING SEARCH (Calegari-Loukidou, Zippers, Thm 4.9).  K = ker phi.  For a step
    radius c let S_c = { s in K, s != 1 : d(o, s o) <= c }, and fix t with phi(t) = 1.  A
    breadth-first search of K with steps S_c, inside the hyperbolic ball of radius R, looks
    for chains from 1 to t^-1 s t and to t s t^-1 (s in S_c).  These are the roofs one level
    up (resp. down) over the horizontal segment (1, s): the substitution rule of the
    staircase family.  If all of them are found, and every a_i t^-phi(a_i) is reached too,
    then <S_c> is normalised by t and <S_c, t> = Pi, which PROVES that S_c generates K.

    Usage:  chz selftest
            chz ball RHO MARGIN            count B(RHO) found with generators a_i^{+-1}
            chz kernel C R [TPHI]          the block-filling search (t with phi(t) = TPHI); writes subst_C_R_tTPHI.txt

    Copyright Danny Calegari 2026, released under the terms of the GNU GPL.
*/


