static int selftest()
{
    printf("exact checks in Z[zeta_12] (primed coordinates)\n");
    const char* nm[4] = {"u'", "v'", "b'", "j"};
    M3 X[4] = {U, V, B, J};
    for (int i = 0; i < 4; i++) {
        M3 W = mmul(mmul(madj(X[i]), FP), X[i]);
        printf("  %s unitary for F': %s\n", nm[i], meq(W, FP) ? "yes" : "NO");
    }
    M3 Ui = minv(U), Vi = minv(V), Bi = minv(B);
    printf("  u u^-1 = 1: %s\n", meq(mmul(U, Ui), mid()) ? "yes" : "NO");
    struct { const char* s; M3 m; } rel[] = {
        {"u^3", mpow(U,3)}, {"v^4", mpow(V,4)}, {"b^3", mpow(B,3)},
        {"(uv)^2 (vu)^-2", mmul(mpow(mmul(U,V),2), minv(mpow(mmul(V,U),2)))},
        {"v b v^-1 b^-1", mmul(mmul(mmul(V,B),Vi),Bi)},
        {"(buv)^3", mpow(mmul(mmul(B,U),V),3)},
        {"(buvu)^2 v", mmul(mpow(mmul(mmul(mmul(B,U),V),U),2), V)},
        {"(uv)^2 j^-1", mmul(mpow(mmul(U,V),2), minv(J))},
    };
    for (auto& r : rel) {
        int k = mscalar(r.m);
        if (k >= 0) printf("  %-16s = zeta^%d  I\n", r.s, k);
        else printf("  %-16s is NOT scalar\n", r.s);
    }
    for (int i = 0; i < 3; i++) {
        M3 W = mmul(mmul(madj(A[i]), FP), A[i]);
        printf("  a%d unitary for F': %s   d(o, a%d o) = %.6f\n", i+1, meq(W, FP) ? "yes" : "NO", i+1, hdist(A[i].e[2][2]));
    }
    M3 J4 = mpow(J,4), J4i = minv(J4);
    M3 a1 = A[0], a2 = A[1], a3 = A[2], a1i = minv(a1), a2i = minv(a2), a3i = minv(a3);
    M3 l1 = mmul(mmul(J4, a1), J4i), r1 = mmul(mmul(mmul(a3, mpow(a2,-3)), mpow(a3,3)), a1);
    M3 l2 = mmul(mmul(J4, a2), J4i), r2 = a3i;
    M3 l3 = mmul(mmul(J4, a3), J4i);
    M3 r3 = mmul(mmul(mmul(mmul(mmul(mmul(mmul(mmul(mmul(mmul(a1i, a2i), a1), mpow(a2,2)), a1i), a2i), a1), a3i), a1i), a2), a1);
    printf("  j^4 a1 j^-4 = a3 a2^-3 a3^3 a1 : %s\n", mscalar(mmul(l1, minv(r1))) >= 0 ? "yes" : "NO");
    printf("  j^4 a2 j^-4 = a3^-1             : %s\n", mscalar(mmul(l2, minv(r2))) >= 0 ? "yes" : "NO");
    printf("  j^4 a3 j^-4 = (CKY's word)      : %s\n", mscalar(mmul(l3, minv(r3))) >= 0 ? "yes" : "NO");
    // the Galois conjugate (zeta -> zeta^5) must be bounded: F' is definite there
    double mx = 0;
    for (int i = 0; i < 3; i++) for (int j = 0; j < 3; j++) mx = std::max(mx, std::abs(zval(mpow(a1,20).e[i][j], ZETA5)));
    printf("  max |entry| of a1^20 under zeta -> zeta^5: %.3f (bounded, as it must be)\n", mx);
    return 0;
}

static int ballmode(double rho, double margin, bool geo)
{
    vector<Gen> G = geo ? geogens(4.5) : agens();
    if (geo) printf("geometric generators: the %zu elements of B(4.5) \\ {1}\n", G.size());
    Store S;
    double t0 = now();
    guard(rho + margin);
    long bad = enumerate(S, G, rho + margin);
    printf("enumerated %zu elements with d <= %.2f in %.2fs; f-inconsistencies: %ld\n",
           S.size(), rho + margin, now() - t0, bad);
    printf("   r     #B(r)   sinh^4(r/2)   ratio\n");
    for (double r = 1; r <= rho + 1e-9; r += 0.5) {
        long n = 0;
        for (size_t i = 0; i < S.size(); i++) if (S.dist[i] <= r) n++;
        double e = pow(sinh(r/2), 4);
        printf("  %4.1f %9ld %12.1f   %.4f\n", r, n, e, n/e);
    }
    // the shortest elements, and whether their inverses were found
    printf("elements with d <= 3.2:\n");
    for (size_t i = 0; i < S.size(); i++) if (S.dist[i] <= 3.2) {
        int ii = S.lookup(minv(S.load(i)));
        printf("  d = %.6f  f = (%d,%d)  inverse %s  %s\n", S.dist[i], S.f0[i], S.f1[i],
               ii >= 0 ? "found" : "MISSING", word(S, i, G).c_str());
    }
    // distribution of phi = f0 on B(rho)
    vector<long> hist(81, 0);
    for (size_t i = 0; i < S.size(); i++) if (S.dist[i] <= rho) { int v = S.f0[i]; if (v >= -40 && v <= 40) hist[v+40]++; }
    printf("phi on B(%.1f):", rho);
    for (int v = -40; v <= 40; v++) if (hist[v+40]) printf(" %d:%ld", v, hist[v+40]);
    printf("\n");
    return 0;
}

// roof lengths, and the Perron-Frobenius root of the substitution (the growth rate of
// |theta^n(s)|), by power iteration
static void stats(const vector<vector<int>>& w, const vector<char>& ok, const char* nm)
{
    size_t mx = 0, mn = (size_t)-1;
    double sum = 0;
    long n = 0;
    for (size_t j = 0; j < w.size(); j++)
        if (ok[j]) { mx = std::max(mx, w[j].size()); mn = std::min(mn, w[j].size()); sum += w[j].size(); n++; }
    if (!n) return;
    printf("%s roof lengths (in S_c-steps): min %zu, mean %.2f, max %zu", nm, mn, sum/n, mx);
    if ((size_t)n < w.size()) { printf("\n"); return; }
    vector<double> x(w.size(), 1.0), y(w.size());
    double lam = 0;
    for (int it = 0; it < 300; it++) {
        std::fill(y.begin(), y.end(), 0.0);
        for (size_t j = 0; j < w.size(); j++) for (int l : w[j]) y[j] += x[l];
        double sx = 0, sy = 0;
        for (size_t j = 0; j < w.size(); j++) { sx += x[j]; sy += y[j]; }
        lam = sy/sx;
        for (size_t j = 0; j < w.size(); j++) x[j] = y[j]/sy*w.size();
    }
    printf(";  growth rate of the substitution %.4f\n", lam);
}

static void writesubst(const char* fn, double c, double R, const string& tw, const vector<Gen>& S,
                       const vector<vector<int>>& up, const vector<vector<int>>& down, const vector<vector<int>>& mw)
{
    FILE* f = fopen(fn, "w");
    if (!f) { perror(fn); return; }
    fprintf(f, "# chz block-filling data: Cartwright-Steger Pi, phi = first coordinate of f\n");
    fprintf(f, "# c %.4f  R %.4f\n", c, R);
    fprintf(f, "t %s\n", tw.c_str());
    fprintf(f, "S %zu\n", S.size());
    for (size_t j = 0; j < S.size(); j++)
        fprintf(f, "%zu  d=%.6f  f2=%d  %s\n", j, hdist(S[j].m.e[2][2]), S[j].f1, S[j].name.c_str());
    fprintf(f, "up      # t^-1 s_j t = product of the listed s's\n");
    for (size_t j = 0; j < S.size(); j++) { fprintf(f, "%zu:", j); for (int l : up[j]) fprintf(f, " %d", l); fprintf(f, "\n"); }
    fprintf(f, "down    # t s_j t^-1 = product of the listed s's\n");
    for (size_t j = 0; j < S.size(); j++) { fprintf(f, "%zu:", j); for (int l : down[j]) fprintf(f, " %d", l); fprintf(f, "\n"); }
    fprintf(f, "member  # a_i t^-phi(a_i) = product of the listed s's\n");
    for (int i = 0; i < 3; i++) { fprintf(f, "a%d:", i+1); for (int l : mw[i]) fprintf(f, " %d", l); fprintf(f, "\n"); }
    fclose(f);
}

// Convergence of the staircase chains.  The level-n chain over the segment (1, s_y) is the
// sequence of points t^n u o, u running over the prefixes of theta^n(s_y); it goes from t^n o
// to s_y t^n o, and its limit is the arc of the zipper from t^+ to s_y t^+.  Reports the
// largest chord between consecutive points (radially projected to S^3) at each level.
// Double precision suffices: nothing is identified here.
typedef std::array<std::array<cpx,3>,3> D3;

static D3 todbl(const M3& g)
{
    D3 m;
    for (int i = 0; i < 3; i++) for (int j = 0; j < 3; j++) m[i][j] = zval(g.e[i][j]);
    return m;
}

static D3 dmul(const D3& a, const D3& b)
{
    D3 c;
    for (int i = 0; i < 3; i++) for (int j = 0; j < 3; j++) c[i][j] = a[i][0]*b[0][j] + a[i][1]*b[1][j] + a[i][2]*b[2][j];
    return c;
}

static void sphpoint(const D3& m, double s[4], double& d)
{
    cpx c[3] = {m[0][2], m[1][2], m[2][2]};
    double p[4];
    ballpoint(c, p);
    double n = sqrt(p[0]*p[0] + p[1]*p[1] + p[2]*p[2] + p[3]*p[3]);
    for (int i = 0; i < 4; i++) s[i] = p[i]/n;
    double a = std::abs(m[2][2]);
    d = a <= 1 ? 0 : 2*acosh(a);          // d(o, g o) = 2 acosh |g_33|, accurate near S^3
}

static void convergence(const vector<Gen>& S, const vector<vector<int>>& th, const M3& t, int y, size_t Lmax, const char* nm)
{
    printf("convergence of the chains for %s over the segment (1, s_%d):\n", nm, y);
    printf("   n    #points   max chord on S^3   d(o, chain) min..max\n");
    vector<D3> Sd;
    for (auto& s : S) Sd.push_back(todbl(s.m));
    D3 td = todbl(t), T = todbl(mid());
    vector<int> w = {y};
    for (int n = 0; n < 40; n++) {
        D3 P = T;
        double prev[4], cur[4], d, dmin, dmax, mc = 0;
        sphpoint(P, prev, d);
        dmin = dmax = d;
        for (size_t m = 0; m < w.size(); m++) {
            P = dmul(P, Sd[w[m]]);
            sphpoint(P, cur, d);
            dmin = std::min(dmin, d); dmax = std::max(dmax, d);
            double e = 0;
            for (int i = 0; i < 4; i++) e += (cur[i]-prev[i])*(cur[i]-prev[i]);
            mc = std::max(mc, sqrt(e));
            memcpy(prev, cur, sizeof prev);
        }
        printf("  %2d %10zu   %14.3e   %7.2f .. %.2f\n", n, w.size() + 1, mc, dmin, dmax);
        size_t next = 0;
        for (int l : w) next += th[l].size();
        if (next > Lmax || dmax > 34) break;      // 34: double precision is still ample
        vector<int> w2;
        w2.reserve(next);
        for (int l : w) for (int x : th[l]) w2.push_back(x);
        w.swap(w2);
        T = dmul(T, td);
    }
}

static int kernelmode(double c, double R, int tphi, double rho = 5.0, double margin = 0.5)
{
    double t0 = now();
    vector<Gen> G = geogens(4.5);
    Store Ball;
    rho = std::max(rho, c);
    guard(rho + margin);
    long bad = enumerate(Ball, G, rho + margin);
    printf("small ball: %zu elements with d <= %.2f (%.2fs), f-inconsistencies %ld\n", Ball.size(), rho + margin, now() - t0, bad);

    // t: the shortest element with phi = 1
    int ti = -1;
    for (size_t i = 0; i < Ball.size(); i++)
        if (Ball.f0[i] == 1 && (ti < 0 || Ball.dist[i] < Ball.dist[ti])) ti = i;
    if (ti < 0) { printf("no element with phi = 1 in the small ball\n"); return 1; }
    M3 t = Ball.load(ti), ti_ = minv(t);
    printf("t = %s   d(o,t o) = %.4f   f(t) = (%d,%d)\n", word(Ball, ti, G).c_str(), Ball.dist[ti], Ball.f0[ti], Ball.f1[ti]);

    // S_c
    vector<int> Sidx;
    for (size_t i = 1; i < Ball.size(); i++) if (Ball.f0[i] == 0 && Ball.dist[i] <= c) Sidx.push_back(i);
    std::sort(Sidx.begin(), Sidx.end(), [&](int a, int b) { return Ball.dist[a] < Ball.dist[b]; });
    vector<Gen> S;
    for (int i : Sidx) S.push_back({Ball.load(i), 0, Ball.f1[i], word(Ball, i, G)});
    printf("|S_c| = %zu kernel elements with d <= %.2f", S.size(), c);
    if (!S.empty()) printf(" (shortest %.4f)", Ball.dist[Sidx[0]]);
    printf("\n");
    if (S.empty()) return 1;

    // breadth-first search of K with steps S_c inside B(R)
    Store Kst;
    t0 = now();
    Kst.add(mnormal(mid()), -1, -1, 0, 0, 0, 0.f);
    long badk = 0;
    const size_t CAP = 2000000;          // about 340 MB
    i64 key[12];
    Zz col[3];
    bool capped = false;
    for (size_t q = 0; q < Kst.size() && !capped; q++) {
        M3 g = Kst.load(q);
        for (size_t j = 0; j < S.size(); j++) {
            int k = prodkey(g, S[j].m, key, col);
            int a1 = Kst.f1[q] + S[j].f1;
            int f = Kst.find(key);
            if (f >= 0) { if (Kst.f1[f] != a1) badk++; continue; }
            double d = hdist(col[2]);
            if (d > R) continue;
            M3 h = mrotk(mmul(g, S[j].m), k);
            Kst.add(h, q, j, Kst.depth[q] + 1, 0, a1, (float)d);
            if (Kst.size() >= CAP) { capped = true; break; }
        }
    }
    int maxdep = 0;
    for (size_t i = 0; i < Kst.size(); i++) maxdep = std::max(maxdep, Kst.depth[i]);
    printf("K-search: %zu elements of K reached inside B(%.2f) in %.2fs, max S_c-length %d, f-inconsistencies %ld%s\n",
           Kst.size(), R, now() - t0, maxdep, badk, capped ? "  [CAPPED]" : "");

    // the certificate
    long upfound = 0, downfound = 0;
    vector<vector<int>> up(S.size()), down(S.size());
    vector<char> uok(S.size(), 0), dok(S.size(), 0);
    for (size_t j = 0; j < S.size(); j++) {
        int iu = Kst.lookup(mmul(mmul(ti_, S[j].m), t));
        int id = Kst.lookup(mmul(mmul(t, S[j].m), ti_));
        if (iu >= 0) { up[j] = Kst.path(iu); uok[j] = 1; upfound++; }
        if (id >= 0) { down[j] = Kst.path(id); dok[j] = 1; downfound++; }
    }
    printf("roofs up   (t^-1 s t): %ld / %zu found\n", upfound, S.size());
    printf("roofs down (t s t^-1): %ld / %zu found\n", downfound, S.size());
    int memb = 0;
    vector<vector<int>> mw(3);
    for (int i = 0; i < 3; i++) {
        int ia = Kst.lookup(mmul(A[i], mpow(t, -FA[i][0])));
        if (ia >= 0) { memb++; mw[i] = Kst.path(ia); }
        printf("a%d t^%d in <S_c>: %s\n", i+1, -FA[i][0], ia >= 0 ? "yes" : "not reached");
    }
    bool cert = upfound == (long)S.size() && downfound == (long)S.size() && memb == 3;
    printf("CERTIFICATE that S_c generates K: %s\n", cert ? "YES" : "no");

    // roof length statistics and the growth rate of the substitution
    stats(up, uok, "up  ");
    stats(down, dok, "down");
    if (!cert) return 2;

    // The vertical step need not climb just one level: any t with phi(t) > 0 normalises K,
    // and t^-1 s t is again a word in S_c.  A steep t (phi(t) = tphi > 1) climbs faster.
    if (tphi != 1) {
        ti = -1;
        for (size_t i = 0; i < Ball.size(); i++)
            if (Ball.f0[i] == tphi && (ti < 0 || Ball.dist[i] < Ball.dist[ti])) ti = i;
        if (ti < 0) { printf("no element with phi = %d in the small ball\n", tphi); return 1; }
        t = Ball.load(ti); ti_ = minv(t);
        printf("steep t = %s   d(o,t o) = %.4f   f(t) = (%d,%d)\n", word(Ball, ti, G).c_str(), Ball.dist[ti], Ball.f0[ti], Ball.f1[ti]);
        upfound = downfound = 0;
        for (size_t j = 0; j < S.size(); j++) {
            int iu = Kst.lookup(mmul(mmul(ti_, S[j].m), t));
            int id = Kst.lookup(mmul(mmul(t, S[j].m), ti_));
            uok[j] = iu >= 0; dok[j] = id >= 0;
            up[j] = iu >= 0 ? Kst.path(iu) : vector<int>();
            down[j] = id >= 0 ? Kst.path(id) : vector<int>();
            upfound += uok[j]; downfound += dok[j];
        }
        printf("steep roofs up %ld / %zu, down %ld / %zu\n", upfound, S.size(), downfound, S.size());
        stats(up, uok, "up  ");
        stats(down, dok, "down");
        if (upfound < (long)S.size() || downfound < (long)S.size()) return 2;
    }

    char fn[64];
    snprintf(fn, sizeof fn, "subst_%.2f_%.2f_t%d.txt", c, R, tphi);
    writesubst(fn, c, R, word(Ball, ti, G), S, up, down, mw);
    printf("wrote %s\n", fn);

    convergence(S, up, t, 0, 400000, "Z+ (t, theta_up)");
    convergence(S, down, ti_, 0, 400000, "Z- (t^-1, theta_down)");
    return 0;
}

int main(int argc, char** argv)
{
    setup();
    if (argc >= 2 && !strcmp(argv[1], "selftest")) return selftest();
    if (argc >= 4 && !strcmp(argv[1], "ball")) return ballmode(atof(argv[2]), atof(argv[3]), argc >= 5 && !strcmp(argv[4], "geo"));
    if (argc >= 4 && !strcmp(argv[1], "kernel"))
        return kernelmode(atof(argv[2]), atof(argv[3]), argc >= 5 ? atoi(argv[4]) : 1);
    fprintf(stderr, "usage: chz selftest | ball RHO MARGIN [geo] | kernel C R [TPHI]\n");
    return 1;
}
