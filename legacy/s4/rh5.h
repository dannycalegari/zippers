/*  rh5.h  --  exact arithmetic for a fibered hyperbolic 5-manifold: the right-angled Coxeter
    group W of the polytope P5 in H^5, with the colouring, moves and balanced state of
    Italiano-Martelli-Migliorini, "Hyperbolic 5-manifolds that fiber over S^1" (arXiv:2105.14795,
    Invent. Math. 2023).

    THE POLYTOPE.  In the Klein model P5 = { x : s.x <= 1 for the 16 sign vectors s in {+-1}^5
    with an even number of minus signs }.  In the hyperboloid model (form x1^2+...+x5^2 - x6^2)
    the facet s has the unit normal v_s = (s, 1)/2.  Facets at Hamming distance 2 are orthogonal,
    and at distance 4 they are tangent at infinity, so P5 is right-angled, with 10 ideal
    vertices (+-e_i) and 16 finite ones (o/3, o odd).  W is generated by the 16 reflections
    r_s = I - 2 v_s v_s^T J.  It preserves the lattice Z^6 u (Z^6 + (1/2,...,1/2)), so every
    element has entries in (1/2)Z: an element is stored as TWICE its matrix, and all
    arithmetic is exact.  W acts simply transitively on the tiles, and o = e_6 (the centre of
    P5) has trivial stabiliser, so an element is determined by g o, its last column: the key.
    d(o, g o) = acosh g_66.

    THE MAP TO Z (IMM sections 1.3-1.9).  The colouring gives the facets s and s' (s with its
    first four signs reversed) the same colour; the colours are those of IMM Figure 3.  The
    moves are {1,5}, {2,6}, {3,7}, {4,8}, and the initial state is the balanced state of IMM
    Figure 9 (status I or O for each facet).  In the tile g P5 the state is the initial one with
    the status of the facets of move m reversed when mu_m(g) = 1, where mu: W -> (Z/2)^4 counts
    (mod 2) the reflections of each move in a word for g.  Crossing a facet from the side where
    its status is O to the side where it is I raises the height h by 1, and the other way
    lowers it by 1.  This is a cocycle (it is checked whenever an element is reached by two
    paths), so h: W -> Z is well defined with h(1) = 0.  On the normal subgroup
    Gamma = ker mu (index 16; it contains pi_1 of IMM's manifold M5) it is a homomorphism,
    h(gk) = h(g) + h(k), and it is even; phi = h/2 is the fibration of M5 (up to the degree-2
    lift that IMM also take).  K = ker phi.

    Copyright Danny Calegari 2026, released under the terms of the GNU GPL.
*/

