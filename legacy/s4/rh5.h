typedef long long i64;

static double now()
{
    return std::chrono::duration<double>(std::chrono::steady_clock::now().time_since_epoch()).count();
}

static inline uint64_t splitmix(uint64_t x)
{
    x += 0x9e3779b97f4a7c15ULL;
    x = (x ^ (x >> 30)) * 0xbf58476d1ce4e5b9ULL;
    x = (x ^ (x >> 27)) * 0x94d049bb133111ebULL;
    return x ^ (x >> 31);
}

struct M6 { i64 e[6][6]; };          // twice the matrix

static M6 m6id()
{
    M6 m;
    memset(&m, 0, sizeof m);
    for (int i = 0; i < 6; i++) m.e[i][i] = 2;
    return m;
}

static M6 m6mul(const M6& a, const M6& b)
{
    M6 c;
    for (int i = 0; i < 6; i++)
        for (int j = 0; j < 6; j++) {
            __int128 s = 0;
            for (int k = 0; k < 6; k++) s += (__int128)a.e[i][k]*b.e[k][j];
            if (s & 1) { fprintf(stderr, "m6mul: an odd entry (not in the lattice)\n"); exit(1); }
            c.e[i][j] = (i64)(s/2);
        }
    return c;
}

static M6 m6inv(const M6& a)           // g^-1 = J g^T J
{
    M6 c;
    for (int i = 0; i < 6; i++)
        for (int j = 0; j < 6; j++) c.e[i][j] = a.e[j][i]*((i == 5) != (j == 5) ? -1 : 1);
    return c;
}

static bool m6eq(const M6& a, const M6& b) { return !memcmp(&a, &b, sizeof a); }

static inline double m6dist(const M6& g)  // d(o, g o) = acosh g_66
{
    double c = 0.5*(double)g.e[5][5];
    return c <= 1 ? 0 : std::acosh(c);
}

static i64 m6maxcoef(const M6& g)
{
    i64 m = 0;
    for (int i = 0; i < 6; i++) for (int j = 0; j < 6; j++) m = std::max(m, std::llabs(g.e[i][j]));
    return m;
}

// ---------------------------------------------------------------------------------------
// The facets, in the order: colour 1 (status I, O), colour 2 (I, O), ..., colour 8 (I, O).
// The first facet of each colour has status I in the initial state (IMM Figure 9).

static const char* FACET_NAME[16] = {
    "+++++", "----+",   "-+-++", "+-+-+",   "+--++", "-++-+",   "++--+", "--+++",
    "-+++-", "+----",   "---+-", "+++--",   "+-++-", "-+---",   "++-+-", "--+--" };

static int FS[16][5];                  // the sign vectors
static int COLOUR[16];                 // 0..7 (IMM's colour minus 1)
static int MOVE[16];                   // 0..3: the move {t, t+4} containing the colour
static int INIT_I[16];                 // 1 if the status is I in the initial state
static M6 REF[16];                     // twice the reflections

static void rh5_setup()
{
    for (int f = 0; f < 16; f++) {
        for (int k = 0; k < 5; k++) FS[f][k] = FACET_NAME[f][k] == '+' ? 1 : -1;
        COLOUR[f] = f/2;
        MOVE[f] = COLOUR[f] % 4;
        INIT_I[f] = (f % 2 == 0);
        int a[6] = {FS[f][0], FS[f][1], FS[f][2], FS[f][3], FS[f][4], 1};
        for (int i = 0; i < 6; i++)
            for (int j = 0; j < 6; j++) REF[f].e[i][j] = (i == j ? 2 : 0) - a[i]*a[j]*(j == 5 ? -1 : 1);
    }
    // checks: even sign vectors, a proper colouring, s and s' share a colour, the quartets
    // (colours t, t+4: facets differing exactly in positions t and 5), the balanced state
    int bad = 0;
    for (int f = 0; f < 16; f++) {
        int neg = 0;
        for (int k = 0; k < 5; k++) neg += FS[f][k] < 0;
        if (neg % 2) bad++;
        if (!m6eq(m6mul(REF[f], REF[f]), m6id())) bad++;
    }
    for (int f = 0; f < 16; f++)
        for (int g = f + 1; g < 16; g++) {
            int d = 0, pos[5], np = 0;
            for (int k = 0; k < 5; k++) if (FS[f][k] != FS[g][k]) { d++; pos[np++] = k; }
            if (d == 2 && COLOUR[f] == COLOUR[g]) bad++;                        // adjacent, same colour
            if (COLOUR[f] == COLOUR[g] && !(d == 4 && FS[f][4] == FS[g][4])) bad++;     // the pairs s, s'
            if (d == 2 && MOVE[f] == MOVE[g]) {                                  // an adjacent pair of a quartet
                if (!(pos[0] == MOVE[f] && pos[1] == 4)) bad++;
                if (INIT_I[f] != INIT_I[g]) bad++;                                // balanced
            }
            // orthogonal (d=2) reflections commute
            if (d == 2 && !m6eq(m6mul(REF[f], REF[g]), m6mul(REF[g], REF[f]))) bad++;
        }
    if (bad) { fprintf(stderr, "rh5_setup: %d checks failed\n", bad); exit(1); }
}

// the height step for crossing facet f out of a tile whose move parities are mu
static inline int hstep(int mu, int f)
{
    int statusI = INIT_I[f] ^ ((mu >> MOVE[f]) & 1);
    return statusI ? -1 : +1;
}

// mu and h of a word (facet letters), starting from the identity
static inline void word_mu_h(const vector<int>& w, int& mu, int& h)
{
    mu = 0; h = 0;
    for (int f : w) { h += hstep(mu, f); mu ^= 1 << MOVE[f]; }
}

static M6 word_matrix(const vector<int>& w)
{
    M6 g = m6id();
    for (int f : w) g = m6mul(g, REF[f]);
    return g;
}

// ---------------------------------------------------------------------------------------
// A store of group elements, keyed by g o (the last column of 2g), with the parent and letter
// of the path that reached them (a facet for W, a generator index for K), mu, h, and d(o, g o).

struct Store6 {
    vector<int32_t> mat;                // 36 entries per element (they are small)
    vector<int> parent, letter, depth, mu, h;
    vector<float> dist;
    vector<int64_t> table;              // open addressing: index + 1, 0 = empty
    uint64_t mask = 0;

    Store6() { table.assign(1 << 16, 0); mask = table.size() - 1; }
    size_t size() const { return parent.size(); }

    static uint64_t hkey(const i64* col)
    {
        uint64_t x = 0x243f6a8885a308d3ULL;
        for (int i = 0; i < 6; i++) x = splitmix(x ^ (uint64_t)col[i]);
        return x;
    }
    void col(size_t i, i64 c[6]) const { for (int r = 0; r < 6; r++) c[r] = mat[36*i + 6*r + 5]; }
    M6 load(size_t i) const
    {
        M6 g;
        for (int r = 0; r < 6; r++) for (int c = 0; c < 6; c++) g.e[r][c] = mat[36*i + 6*r + c];
        return g;
    }
    int find(const i64* c) const
    {
        for (uint64_t p = hkey(c) & mask; table[p]; p = (p + 1) & mask) {
            size_t i = table[p] - 1;
            bool eq = true;
            for (int r = 0; r < 6 && eq; r++) eq = mat[36*i + 6*r + 5] == c[r];
            if (eq) return (int)i;
        }
        return -1;
    }
    int lookup(const M6& g) const { i64 c[6]; for (int r = 0; r < 6; r++) c[r] = g.e[r][5]; return find(c); }
    void grow()
    {
        vector<int64_t> old;
        old.swap(table);
        table.assign(2*old.size(), 0);
        mask = table.size() - 1;
        for (int64_t v : old) if (v) {
            i64 c[6];
            col(v - 1, c);
            uint64_t p = hkey(c) & mask;
            while (table[p]) p = (p + 1) & mask;
            table[p] = v;
        }
    }
    int add(const M6& g, int par, int let, int dep, int m, int hh, float d)
    {
        if (2*(size() + 1) > table.size()) grow();
        for (int r = 0; r < 6; r++) for (int c = 0; c < 6; c++) {
            i64 v = g.e[r][c];
            if (v > INT32_MAX || v < INT32_MIN) { fprintf(stderr, "Store6: entry too large\n"); exit(1); }
            mat.push_back((int32_t)v);
        }
        parent.push_back(par); letter.push_back(let); depth.push_back(dep);
        mu.push_back(m); h.push_back(hh); dist.push_back(d);
        i64 c[6];
        for (int r = 0; r < 6; r++) c[r] = g.e[r][5];
        uint64_t p = hkey(c) & mask;
        while (table[p]) p = (p + 1) & mask;
        table[p] = (int64_t)size();
        return (int)size() - 1;
    }
    vector<int> path(int i) const      // the letters from the root to element i
    {
        vector<int> w;
        for (; i > 0 && parent[i] >= 0; i = parent[i]) w.push_back(letter[i]);
        std::reverse(w.begin(), w.end());
        return w;
    }
};

// refuse balls that would not fit: #B(rho) is about 0.39 e^{4 rho} tiles
static void guard6(double rho, double maxcount = 4e6)
{
    double est = 0.39*std::exp(4*rho);
    if (est > maxcount) {
        fprintf(stderr, "refusing B(%.2f): about %.3g elements (limit %.3g)\n", rho, est, maxcount);
        exit(1);
    }
}

// Best-first enumeration of the tiles g P5 with d(o, g o) <= rho, by facet crossings.  Every
// element is reached along a gallery of tiles with centres within rho.  Counts the elements
// reached twice with different (mu, h): a nonzero count would mean that h is not a cocycle.
static long enumerate6(Store6& B, double rho)
{
    long bad = 0;
    B = Store6();
    B.add(m6id(), -1, -1, 0, 0, 0, 0.f);
    typedef std::pair<float, int> QE;
    std::priority_queue<QE, vector<QE>, std::greater<QE>> q;
    q.push({0.f, 0});
    vector<char> done(1, 0);
    while (!q.empty()) {
        int i = q.top().second;
        q.pop();
        if (done[i]) continue;
        done[i] = 1;
        M6 g = B.load(i);
        int mu = B.mu[i], hh = B.h[i];
        for (int f = 0; f < 16; f++) {
            M6 x = m6mul(g, REF[f]);
            int m2 = mu ^ (1 << MOVE[f]), h2 = hh + hstep(mu, f);
            int k = B.lookup(x);
            if (k >= 0) { if (B.mu[k] != m2 || B.h[k] != h2) bad++; continue; }
            double d = m6dist(x);
            if (d > rho) continue;
            int j = B.add(x, i, f, B.depth[i] + 1, m2, h2, (float)d);
            done.push_back(0);
            q.push({(float)d, j});
        }
    }
    return bad;
}

static string fword(const vector<int>& w)
{
    string s;
    for (size_t i = 0; i < w.size(); i++) { if (i) s += " "; s += std::to_string(w[i]); }
    return w.empty() ? string("1") : s;
}
