static int selftest()
{
    // the data of the example, under their legacy names
    const M3 &U = cs::U, &V = cs::V, &B = cs::B, &J = cs::J;
    const M3* A = cs::A;
    printf("exact checks in Z[zeta_12] (primed coordinates)\n");
    const char* nm[4] = {"u'", "v'", "b'", "j"};
    M3 X[4] = {U, V, B, J};
    for (int i = 0; i < 4; i++) {
        M3 W = mmul(mmul(madj(X[i]), FP), X[i]);
        printf("  %s unitary for F': %s\n", nm[i], meq(W, FP) ? "yes" : "NO");
    }
    M3 Ui = minv(U), Vi = minv(V), Bi = minv(B);
    printf("  u u^-1 = 1: %s\n", meq(mmul(U, Ui), mid()) ? "yes" : "NO");
    struct { const char* s; M3 m; } rel[] = {
        {"u^3", mpow(U,3)}, {"v^4", mpow(V,4)}, {"b^3", mpow(B,3)},
        {"(uv)^2 (vu)^-2", mmul(mpow(mmul(U,V),2), minv(mpow(mmul(V,U),2)))},
        {"v b v^-1 b^-1", mmul(mmul(mmul(V,B),Vi),Bi)},
        {"(buv)^3", mpow(mmul(mmul(B,U),V),3)},
        {"(buvu)^2 v", mmul(mpow(mmul(mmul(mmul(B,U),V),U),2), V)},
        {"(uv)^2 j^-1", mmul(mpow(mmul(U,V),2), minv(J))},
    };
    for (auto& r : rel) {
        int k = mscalar(r.m);
        if (k >= 0) printf("  %-16s = zeta^%d  I\n", r.s, k);
        else printf("  %-16s is NOT scalar\n", r.s);
    }
    for (int i = 0; i < 3; i++) {
        M3 W = mmul(mmul(madj(A[i]), FP), A[i]);
        printf("  a%d unitary for F': %s   d(o, a%d o) = %.6f\n", i+1, meq(W, FP) ? "yes" : "NO", i+1, hdist(A[i].e[2][2]));
    }
    M3 J4 = mpow(J,4), J4i = minv(J4);
    M3 a1 = A[0], a2 = A[1], a3 = A[2], a1i = minv(a1), a2i = minv(a2), a3i = minv(a3);
    M3 l1 = mmul(mmul(J4, a1), J4i), r1 = mmul(mmul(mmul(a3, mpow(a2,-3)), mpow(a3,3)), a1);
    M3 l2 = mmul(mmul(J4, a2), J4i), r2 = a3i;
    M3 l3 = mmul(mmul(J4, a3), J4i);
    M3 r3 = mmul(mmul(mmul(mmul(mmul(mmul(mmul(mmul(mmul(mmul(a1i, a2i), a1), mpow(a2,2)), a1i), a2i), a1), a3i), a1i), a2), a1);
    printf("  j^4 a1 j^-4 = a3 a2^-3 a3^3 a1 : %s\n", mscalar(mmul(l1, minv(r1))) >= 0 ? "yes" : "NO");
    printf("  j^4 a2 j^-4 = a3^-1             : %s\n", mscalar(mmul(l2, minv(r2))) >= 0 ? "yes" : "NO");
    printf("  j^4 a3 j^-4 = (CKY's word)      : %s\n", mscalar(mmul(l3, minv(r3))) >= 0 ? "yes" : "NO");
    // the Galois conjugate (zeta -> zeta^5) must be bounded: F' is definite there
    double mx = 0;
    for (int i = 0; i < 3; i++) for (int j = 0; j < 3; j++) mx = std::max(mx, std::abs(zval(mpow(a1,20).e[i][j], ZETA5)));
    printf("  max |entry| of a1^20 under zeta -> zeta^5: %.3f (bounded, as it must be)\n", mx);
    return 0;
}

static int ballmode(double rho, double margin, bool geo)
{
    vector<cs::Gen> G = geo ? cs::geogens(4.5) : cs::agens();
    if (geo) printf("geometric generators: the %zu elements of B(4.5) \\ {1}\n", G.size());
    cs::Store S;
    double t0 = now();
    cs::guard(rho + margin);
    long bad = cs::enumerate(S, G, rho + margin);
    printf("enumerated %zu elements with d <= %.2f in %.2fs; f-inconsistencies: %ld\n",
           S.size(), rho + margin, now() - t0, bad);
    printf("   r     #B(r)   sinh^4(r/2)   ratio\n");
    for (double r = 1; r <= rho + 1e-9; r += 0.5) {
        long n = 0;
        for (size_t i = 0; i < S.size(); i++) if (S.dist[i] <= r) n++;
        double e = pow(sinh(r/2), 4);
        printf("  %4.1f %9ld %12.1f   %.4f\n", r, n, e, n/e);
    }
    // the shortest elements, and whether their inverses were found
    printf("elements with d <= 3.2:\n");
    for (size_t i = 0; i < S.size(); i++) if (S.dist[i] <= 3.2) {
        int ii = S.lookup(minv(S.load(i)));
        printf("  d = %.6f  f = (%d,%d)  inverse %s  %s\n", S.dist[i], S.label[i].f0, S.label[i].f1,
               ii >= 0 ? "found" : "MISSING", cs::word(S, i, G).c_str());
    }
    // distribution of phi = f0 on B(rho)
    vector<long> hist(81, 0);
    for (size_t i = 0; i < S.size(); i++) if (S.dist[i] <= rho) { int v = S.label[i].f0; if (v >= -40 && v <= 40) hist[v+40]++; }
    printf("phi on B(%.1f):", rho);
    for (int v = -40; v <= 40; v++) if (hist[v+40]) printf(" %d:%ld", v, hist[v+40]);
    printf("\n");
    return 0;
}

// The block-filling search: the generic search of search/kernel_search.h, with this example's policy
// (examples/cartwright_steger_search.h: the small ball B(rho + margin), rho = max(5, c), margin 0.5, and what chz
// prints and writes).
static int kernelmode(double c, double R, int tphi, const KernelOptions& opt)
{
    cs::SearchPolicy policy;
    return opt.any() ? kernel_search(policy, c, R, tphi, opt) : kernel_search(policy, c, R, tphi);
}

int main(int argc, char** argv)
{
    cs::setup();
    if (argc >= 2 && !strcmp(argv[1], "selftest")) return selftest();
    if (argc >= 4 && !strcmp(argv[1], "ball")) return ballmode(atof(argv[2]), atof(argv[3]), argc >= 5 && !strcmp(argv[4], "geo"));
    if (argc >= 4 && !strcmp(argv[1], "kernel")) {
        // TPHI, if given, is the fourth argument; the options follow (kernel_search.h)
        bool has_tphi = argc >= 5 && strncmp(argv[4], "--", 2);
        KernelOptions opt;
        if (!parse_kernel_options(argc, argv, has_tphi ? 5 : 4, opt)) return 1;
        return kernelmode(atof(argv[2]), atof(argv[3]), has_tphi ? atoi(argv[4]) : 1, opt);
    }
    fprintf(stderr, "usage: chz selftest | ball RHO MARGIN [geo] | kernel C R [TPHI] [--tlist] [--tcand I] [--noinv]"
            " [--roofs [--excess E] [--jexcess e]]\n");
    return 1;
}
