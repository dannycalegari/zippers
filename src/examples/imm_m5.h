// imm_m5.h: the fibered hyperbolic 5-manifold M5 of Italiano-Martelli-Migliorini, "Hyperbolic 5-manifolds that fiber
// over S^1" (arXiv:2105.14795, Invent. Math. 2023): the right-angled Coxeter group W of the polytope P5 in H^5, with
// IMM's colouring, moves and balanced state, the height h and the subgroup Gamma. namespace zippers::imm.
//
// THE POLYTOPE. In the Klein model P5 = { x : s.x <= 1 for the 16 sign vectors s in {+-1}^5 with an even number of
// minus signs }. In the hyperboloid model (form x1^2+...+x5^2 - x6^2) the facet s has the unit normal v_s = (s, 1)/2.
// Facets at Hamming distance 2 are orthogonal, and at distance 4 they are tangent at infinity, so P5 is right-angled,
// with 10 ideal vertices (+-e_i) and 16 finite ones (o/3, o odd). W is generated by the 16 reflections
// r_s = I - 2 v_s v_s^T J. It preserves the lattice Z^6 u (Z^6 + (1/2,...,1/2)), so every element has entries in
// (1/2)Z: the backend is zippers::ON1<5> (geometry/on1/on1.h), which stores twice the matrix. W acts simply
// transitively on the tiles, and o = e_6 (the centre of P5) has trivial stabiliser, so an element is determined by
// g o, its last column: the key. d(o, g o) = acosh g_66.
//
// THE MAP TO Z (IMM sections 1.3-1.9). The colouring gives the facets s and s' (s with its first four signs reversed)
// the same colour; the colours are those of IMM Figure 3. The moves are {1,5}, {2,6}, {3,7}, {4,8}, and the initial
// state is the balanced state of IMM Figure 9 (status I or O for each facet). In the tile g P5 the state is the
// initial one with the status of the facets of move m reversed when mu_m(g) = 1, where mu: W -> (Z/2)^4 counts (mod 2)
// the reflections of each move in a word for g. Crossing a facet from the side where its status is O to the side
// where it is I raises the height h by 1, and the other way lowers it by 1. This is a cocycle (it is checked whenever
// an element is reached by two paths), so h: W -> Z is well defined with h(1) = 0. On the normal subgroup
// Gamma = ker mu (index 16; it contains pi_1 of IMM's manifold M5) it is a homomorphism, h(gk) = h(g) + h(k), and it
// is even; phi = h/2 is the fibration of M5 (up to the degree-2 lift that IMM also take). K = ker phi.
//
// THE WORDS of the substitution files are in the 16 facet reflections, by number (0..15), and "1" for the empty word.
//
// Moved unchanged from legacy/s4/rh5.h (the facets, colouring, moves, initial state and reflections; rh5_setup, here
// setup; hstep, word_mu_h, word_matrix, guard6, enumerate6, fword) and legacy/s4/zipcore5.h (parse_fword,
// find_roots5): static -> inline, the file-scope statics as C++17 inline variables, namespace zippers::imm, the store
// zippers::Store<ON1<5>, MuH> in place of the legacy Store6 (labels .mu, .h in place of the arrays mu, h). One change
// of form: find_roots5 fills two vectors (the roots and their distances) in place of the legacy World5's members
// roots and rootd. One change of result: parse_fword reads facet 1, which the legacy
// reader dropped (see parse_fword).
//
// At the end of the file: the descent checks of the root balls (descents, RootCertificate,
// certify_store5, certify_roots5 and the lines of zipper5 --stats). It verifies; it changes nothing in the search.

