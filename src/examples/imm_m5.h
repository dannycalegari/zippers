typedef ON1<5> O51;
typedef O51::Elem M6;                  // twice the matrix

// the label of an element in a store: its move parities mu (a 4-bit mask) and its height h
struct MuH { int mu, h; };

typedef zippers::Store<O51, MuH> Store6;

// ---------------------------------------------------------------------------------------
// The facets, in the order: colour 1 (status I, O), colour 2 (I, O), ..., colour 8 (I, O).
// The first facet of each colour has status I in the initial state (IMM Figure 9).

inline const char* const FACET_NAME[16] = {
    "+++++", "----+",   "-+-++", "+-+-+",   "+--++", "-++-+",   "++--+", "--+++",
    "-+++-", "+----",   "---+-", "+++--",   "+-++-", "-+---",   "++-+-", "--+--" };

inline int FS[16][5];                  // the sign vectors
inline int COLOUR[16];                 // 0..7 (IMM's colour minus 1)
inline int MOVE[16];                   // 0..3: the move {t, t+4} containing the colour
inline int INIT_I[16];                 // 1 if the status is I in the initial state
inline M6 REF[16];                     // twice the reflections

inline void setup()
{
    for (int f = 0; f < 16; f++) {
        for (int k = 0; k < 5; k++) FS[f][k] = FACET_NAME[f][k] == '+' ? 1 : -1;
        COLOUR[f] = f/2;
        MOVE[f] = COLOUR[f] % 4;
        INIT_I[f] = (f % 2 == 0);
        int a[6] = {FS[f][0], FS[f][1], FS[f][2], FS[f][3], FS[f][4], 1};
        for (int i = 0; i < 6; i++)
            for (int j = 0; j < 6; j++) REF[f].e[i][j] = (i == j ? 2 : 0) - a[i]*a[j]*(j == 5 ? -1 : 1);
    }
    // checks: even sign vectors, a proper colouring, s and s' share a colour, the quartets
    // (colours t, t+4: facets differing exactly in positions t and 5), the balanced state
    int bad = 0;
    for (int f = 0; f < 16; f++) {
        int neg = 0;
        for (int k = 0; k < 5; k++) neg += FS[f][k] < 0;
        if (neg % 2) bad++;
        if (!O51::eq(O51::mul(REF[f], REF[f]), O51::identity())) bad++;
    }
    for (int f = 0; f < 16; f++)
        for (int g = f + 1; g < 16; g++) {
            int d = 0, pos[5], np = 0;
            for (int k = 0; k < 5; k++) if (FS[f][k] != FS[g][k]) { d++; pos[np++] = k; }
            if (d == 2 && COLOUR[f] == COLOUR[g]) bad++;                        // adjacent, same colour
            if (COLOUR[f] == COLOUR[g] && !(d == 4 && FS[f][4] == FS[g][4])) bad++;     // the pairs s, s'
            if (d == 2 && MOVE[f] == MOVE[g]) {                                  // an adjacent pair of a quartet
                if (!(pos[0] == MOVE[f] && pos[1] == 4)) bad++;
                if (INIT_I[f] != INIT_I[g]) bad++;                                // balanced
            }
            // orthogonal (d=2) reflections commute
            if (d == 2 && !O51::eq(O51::mul(REF[f], REF[g]), O51::mul(REF[g], REF[f]))) bad++;
        }
    if (bad) { fprintf(stderr, "rh5_setup: %d checks failed\n", bad); exit(1); }
}

// the height step for crossing facet f out of a tile whose move parities are mu
inline int hstep(int mu, int f)
{
    int statusI = INIT_I[f] ^ ((mu >> MOVE[f]) & 1);
    return statusI ? -1 : +1;
}

// mu and h of a word (facet letters), starting from the identity
inline void word_mu_h(const std::vector<int>& w, int& mu, int& h)
{
    mu = 0; h = 0;
    for (int f : w) { h += hstep(mu, f); mu ^= 1 << MOVE[f]; }
}

inline M6 word_matrix(const std::vector<int>& w)
{
    M6 g = O51::identity();
    for (int f : w) g = O51::mul(g, REF[f]);
    return g;
}

// refuse balls that would not fit: #B(rho) is about 0.39 e^{4 rho} tiles
inline void guard6(double rho, double maxcount = 4e6)
{
    double est = 0.39*std::exp(4*rho);
    if (est > maxcount) {
        fprintf(stderr, "refusing B(%.2f): about %.3g elements (limit %.3g)\n", rho, est, maxcount);
        exit(1);
    }
}

// Best-first enumeration of the tiles g P5 with d(o, g o) <= rho, by facet crossings.  Every
// element is reached along a gallery of tiles with centres within rho.  Counts the elements
// reached twice with different (mu, h): a nonzero count would mean that h is not a cocycle.
inline long enumerate6(Store6& B, double rho)
{
    long bad = 0;
    B = Store6();
    B.add(O51::identity(), -1, -1, 0, MuH{0, 0}, 0.f);
    typedef std::pair<float, int> QE;
    std::priority_queue<QE, std::vector<QE>, std::greater<QE>> q;
    q.push({0.f, 0});
    std::vector<char> done(1, 0);
    while (!q.empty()) {
        int i = q.top().second;
        q.pop();
        if (done[i]) continue;
        done[i] = 1;
        M6 g = B.load(i);
        int mu = B.label[i].mu, hh = B.label[i].h;
        for (int f = 0; f < 16; f++) {
            M6 x = O51::mul(g, REF[f]);
            int m2 = mu ^ (1 << MOVE[f]), h2 = hh + hstep(mu, f);
            int k = B.lookup(x);
            if (k >= 0) { if (B.label[k].mu != m2 || B.label[k].h != h2) bad++; continue; }
            double d = O51::displacement(x);
            if (d > rho) continue;
            int j = B.add(x, i, f, B.depth[i] + 1, MuH{m2, h2}, (float)d);
            done.push_back(0);
            q.push({(float)d, j});
        }
    }
    return bad;
}

// a word in the facets as text: "0 5 8 4", or "1" for the empty word
inline std::string fword(const std::vector<int>& w)
{
    std::string s;
    for (size_t i = 0; i < w.size(); i++) { if (i) s += " "; s += std::to_string(w[i]); }
    return w.empty() ? std::string("1") : s;
}

// the inverse of fword: every token is a facet number, and the word that is exactly "1" (one token, "1") is the empty
// word, as fword writes it. fword writes both the empty word and the one-letter word of facet 1 as "1"; that cannot
// matter for a substitution file, where neither occurs: no element of S_c is 1 or r_1 (S_c lies in K and leaves out
// 1), and t is neither (r_1 is not in Gamma, and phi(t) > 0).
// The legacy reader (legacy/s4/zipcore5.h, which keeps it) skipped every token "1", so it dropped facet 1 from every
// word, and read each word as its image under the homomorphism of W that kills r_1.
inline std::vector<int> parse_fword(const std::string& w)
{
    std::vector<int> r;
    std::vector<std::string> toks;
    std::istringstream is(w);
    std::string tok;
    while (is >> tok) toks.push_back(tok);
    if (toks.size() == 1 && toks[0] == "1") return r;          // the empty word
    for (const std::string& x : toks) {
        int f = atoi(x.c_str());
        if (f < 0 || f >= 16) { fprintf(stderr, "bad facet letter '%s'\n", x.c_str()); exit(1); }
        r.push_back(f);
    }
    return r;
}

// the roots of the renderer: the elements of Gamma in B(R), nearest first, and their distances (legacy find_roots5
// of zipcore5.h, which filled World5::roots and World5::rootd)
inline void find_roots5(double R, std::vector<M6>& roots, std::vector<double>& rootd)
{
    roots.clear(); rootd.clear();
    if (R <= 0) { roots.push_back(O51::identity()); rootd.push_back(0); return; }
    guard6(R + 0.5);
    Store6 B;
    enumerate6(B, R + 0.5);
    std::vector<int> idx;
    for (size_t i = 0; i < B.size(); i++) if (B.label[i].mu == 0 && B.dist[i] <= R) idx.push_back((int)i);
    std::stable_sort(idx.begin(), idx.end(), [&](int a, int b) { return B.dist[a] < B.dist[b]; });
    for (int i : idx) { roots.push_back(B.load(i)); rootd.push_back(B.dist[i]); }
}

// ---------------------------------------------------------------------------------------
// THE DESCENT CHECKS OF THE ROOT BALLS, exact, on the elements a search found (G = 2g); they change nothing in the
// search, which stays as it is:
//   descents(g)              the number of facets f with (G REF[f])_66 < G_66: the facet neighbours g r_f strictly
//                            nearer to o (exact)
//   RootCertificate          what certify_store5 found
//   certify_store5(B, rho, R, c)   the checks on a store made by enumerate6 with radius rho: the identity first, with no
//                            nearer facet neighbour; every other element with one; every facet neighbour within B(rho)
//                            of an element in the store (CLOSED); no key clashes; the computed distance increasing in
//                            G_66; and the roots of radius R kept from it as find_roots5 keeps them
//   certify_roots5(R)        the search of find_roots5 made again (the same elements, in the same order), checked
//   root_certificate_line    the line of zipper5 --stats; root_margin_line: a second line, only when R is within 1e-6
//                            of the distance of an element of W

inline int descents(const M6& g)
{
    int n = 0;
    for (int f = 0; f < 16; f++) if (O51::mul(g, REF[f]).e[5][5] < g.e[5][5]) n++;
    return n;
}

struct RootCertificate {
    double R = 0, rho = 0;             // the radius of the roots, and of the search (R + 0.5); rho = 0: no search (R <= 0)
    size_t searched = 0;               // the elements of W the search found in B(rho)
    size_t roots = 0;                  // those of Gamma (mu = 0) with d <= R: the roots, as find_roots5 keeps them
    bool identity_first = true;        // the first element of the store is 1
    int identity_descents = 0;         // facets f with (REF[f])_66 < 2: there must be none
    size_t no_descent = 0;             // elements g != 1 with no facet f such that (G REF[f])_66 < G_66
    size_t not_closed = 0;             // (g, f) with g in the store, d(o, g r_f o) <= rho (computed as enumerate6 does)
                                       // and g r_f not in the store
    size_t key_clashes = 0;            // (g, f) with g r_f not in the store, but another element with its key (g r_f o)
    size_t parent_not_nearer = 0;      // elements g != 1 whose parent in the search tree is not strictly nearer
    long label_inconsistencies = 0;    // enumerate6's count: elements reached twice with different (mu, h)
    size_t order_breaks = 0;           // n in [3, max G_66 + 1] where the computed distance of G_66 = n (double, or
                                       // its float) is not above that of n - 1: the ball tests must be monotone in G_66
    int64_t max_g66 = 2;               // the largest G_66 found
    double margin = 1e300;             // |R - d| for the computed distance d of G_66 = n nearest to R (double or float)
    double nearest = 0;                // that d
    std::vector<M6> rootv;             // the roots and their distances, as find_roots5 returns them
    std::vector<double> rootd;
    bool passes() const
    {
        return identity_first && identity_descents == 0 && no_descent == 0 && not_closed == 0 && key_clashes == 0 &&
               order_breaks == 0;
    }
};

// the checks on a store B made by enumerate6 with radius rho, and its roots of radius R (find_roots5's filter and order)
inline void certify_store5(const Store6& B, double rho, double R, RootCertificate& c)
{
    c.R = R;
    c.rho = rho;
    c.searched = B.size();
    c.identity_first = B.size() > 0 && O51::eq(B.load(0), O51::identity()) && B.parent[0] < 0;
    for (size_t i = 0; i < B.size(); i++) {
        M6 g = B.load(i);
        c.max_g66 = std::max<int64_t>(c.max_g66, g.e[5][5]);
        if (i == 0) { c.identity_descents = descents(g); continue; }
        if (descents(g) == 0) c.no_descent++;
        if (B.parent[i] < 0 || B.load(B.parent[i]).e[5][5] >= g.e[5][5]) c.parent_not_nearer++;
    }
    for (size_t i = 0; i < B.size(); i++) {         // the closure, by the key and then the whole element
        M6 g = B.load(i);
        for (int f = 0; f < 16; f++) {
            M6 x = O51::mul(g, REF[f]);
            int k = B.find(O51::key(x));
            if (k >= 0) { if (!O51::eq(B.load(k), x)) c.key_clashes++; }
            else if (!(O51::displacement(x) > rho)) c.not_closed++;
        }
    }
    // the computed distance of an element depends on G_66 = n alone (O51::displacement); it must increase with n,
    // in double (the test of enumerate6) and in float (the stored distances: find_roots5's test and the queue)
    M6 x = O51::identity();
    for (int64_t n = 3; n <= c.max_g66 + 1; n++) {
        x.e[5][5] = n - 1;
        double d0 = O51::displacement(x);
        x.e[5][5] = n;
        double d1 = O51::displacement(x);
        if (!(d1 > d0) || !((float)d1 > (float)d0)) c.order_breaks++;
    }
    // how near R is the distance of an element of W: within single-precision rounding of it, find_roots5's float test
    // (not the exact ball) decides whether those elements are roots
    for (int64_t n = 2; R > 0 && n <= (int64_t)(2*std::cosh(R)) + 2; n++) {
        x.e[5][5] = n;
        double d = O51::displacement(x);
        for (double e : {d, (double)(float)d})
            if (std::fabs(R - e) < c.margin) { c.margin = std::fabs(R - e); c.nearest = d; }
    }
    // the roots, kept as find_roots5 keeps them
    c.rootv.clear(); c.rootd.clear();
    std::vector<int> idx;
    for (size_t i = 0; i < B.size(); i++) if (B.label[i].mu == 0 && B.dist[i] <= R) idx.push_back((int)i);
    std::stable_sort(idx.begin(), idx.end(), [&](int a, int b) { return B.dist[a] < B.dist[b]; });
    for (int i : idx) { c.rootv.push_back(B.load(i)); c.rootd.push_back(B.dist[i]); }
    c.roots = c.rootv.size();
}

// the search of find_roots5 made again (the same calls, so the same elements in the same order), and checked
inline RootCertificate certify_roots5(double R)
{
    RootCertificate c;
    c.R = R;
    if (R <= 0) {                      // find_roots5 draws the identity alone, with no search
        c.roots = 1;
        c.rootv.push_back(O51::identity());
        c.rootd.push_back(0);
        return c;
    }
    double rho = R + 0.5;
    guard6(rho);
    Store6 B;
    c.label_inconsistencies = enumerate6(B, rho);
    certify_store5(B, rho, R, c);
    return c;
}

// the line of zipper5 --stats
inline std::string root_certificate_line(const RootCertificate& c)
{
    char buf[640];
    if (c.rho <= 0) return "roots: 1 (R <= 0: the identity alone, no search)";
    int k = snprintf(buf, sizeof buf, "roots: %zu elements of Gamma in B(%g), of %zu elements of W searched in B(%g); ",
                     c.roots, c.R, c.searched, c.rho);
    std::string s(buf, (size_t)k);
    if (c.passes()) s += "checked: closed under the 16 facet reflections inside that ball, and every "
                           "element descends to 1, both verified exactly";
    else {
        s += "FAILED:";
        if (!c.identity_first) s += " the search does not start at the identity;";
        if (c.identity_descents) { snprintf(buf, sizeof buf, " %d facets bring o nearer to itself;", c.identity_descents); s += buf; }
        if (c.no_descent) { snprintf(buf, sizeof buf, " %zu elements without a nearer facet neighbour;", c.no_descent); s += buf; }
        if (c.not_closed) { snprintf(buf, sizeof buf, " %zu facet neighbours in B(%g) not found;", c.not_closed, c.rho); s += buf; }
        if (c.key_clashes) { snprintf(buf, sizeof buf, " %zu facet neighbours with the key of another element;", c.key_clashes); s += buf; }
        if (c.order_breaks) { snprintf(buf, sizeof buf, " the computed distance is not increasing in G_66 at %zu places;", c.order_breaks); s += buf; }
        s.pop_back();
    }
    if (c.label_inconsistencies) {                // the checks of W may pass, but its labels (mu, h) fail
        snprintf(buf, sizeof buf, "; FAILED for the roots: (mu, h) inconsistent on %ld elements",
                 c.label_inconsistencies);
        s += buf;
    }
    return s;
}

// a second line, only when R is within 1e-6 of the distance of an element of W (empty otherwise)
inline std::string root_margin_line(const RootCertificate& c)
{
    if (c.rho <= 0 || c.margin >= 1e-6) return "";
    char buf[320];
    snprintf(buf, sizeof buf, "roots: R is within %.1e of the distance %.9f of elements of W: whether they are roots is "
             "decided by the single-precision test of find_roots5, not by the exact ball", c.margin, c.nearest);
    return buf;
}

// ---------------------------------------------------------------------------------------
// THE FOCUS CENTRE: an element h of Gamma whose orbit point h o is near the point o_F at distance L from o
// towards the point xi of S^4 (the centre of a zoomed view). Then h B(R) is the ball of radius R about h o (render/
// world.h: the focus ball).
//   1. The tile w P5 of W that contains o_F: from w = 1, while o_F is beyond a facet f of w P5 (<w^-1 o_F, (s_f, 1)> > 0,
//      the facet inequality broken most), cross it: w <- w r_f. Each step crosses a wall that separates w P5 from o_F,
//      so the walk ends (in the tile, or on its boundary).
//   2. The coset: h = w c with mu(c) = mu(w), so that mu(h) = 0 (h in Gamma), c running over the elements of W in
//      B(2.6) (enumerate6) with that mu; the one with h o nearest to o_F.
// Everything is exact except the choices, which are made in doubles. o_F = (sinh(L) xi, cosh(L)) in the hyperboloid
// model, and d(h o, o_F) = acosh(-<h o, o_F>).
// AT A CUSP: when xi is a parabolic fixed point (a cusp of the 5-manifold, as the tips of render/tips.h are), the
// geodesic towards xi ends in the cusp of one tile, whose orbit points stay at a bounded height, so d(h o, o_F) grows
// like L and d(o, h o) stays bounded (docs/developer_guide.md, "Culling").
struct FocusCentre {
    M6 h;                              // in Gamma
    double L = 0;                      // the focus distance
    double dist = 0;                   // d(h o, o_F)
    double disp = 0;                   // d(o, h o)
    int walk = 0;                      // the facets crossed by the walk of step 1
    std::vector<int> word;             // h as a word in the facets: the walk, then c
};

// d(g o, p) for a point p of the hyperboloid model (<p, p> = -1)
inline double orbit_distance(const M6& g, const double p[6])
{
    double s = 0;                      // -<g o, p>: g o is the last column of g = e/2
    for (int i = 0; i < 5; i++) s -= 0.5*(double)g.e[i][5]*p[i];
    s += 0.5*(double)g.e[5][5]*p[5];
    return s <= 1 ? 0 : std::acosh(s);
}

inline FocusCentre focus_centre5(const double xi[5], double L)
{
    double nx = 0;
    for (int k = 0; k < 5; k++) nx += xi[k]*xi[k];
    nx = std::sqrt(nx);
    double p[6];
    for (int k = 0; k < 5; k++) p[k] = std::sinh(L)*xi[k]/nx;
    p[5] = std::cosh(L);
    FocusCentre fc;
    fc.L = L;
    M6 w = O51::identity();
    int mu = 0;
    std::vector<int> word;
    for (int step = 0; step < 100000; step++) {
        // q = w^-1 p = J w^T J p (w = e/2)
        double q[6];
        for (int i = 0; i < 6; i++) {
            double s = 0;
            for (int j = 0; j < 6; j++) s += 0.5*(double)w.e[j][i]*(j == 5 ? -p[j] : p[j]);
            q[i] = i == 5 ? -s : s;
        }
        int best = -1;
        double worst = 1e-12*q[5];
        for (int f = 0; f < 16; f++) {
            double v = -q[5];
            for (int k = 0; k < 5; k++) v += FS[f][k]*q[k];
            if (v > worst) { worst = v; best = f; }
        }
        if (best < 0) break;
        w = O51::mul(w, REF[best]);
        mu ^= 1 << MOVE[best];
        word.push_back(best);
    }
    fc.walk = (int)word.size();
    Store6 B;
    enumerate6(B, 2.6);
    int bi = -1;
    double bd = 1e300;
    for (size_t i = 0; i < B.size(); i++) {
        if (B.label[i].mu != mu) continue;
        double d = orbit_distance(O51::mul(w, B.load(i)), p);
        if (d < bd) { bd = d; bi = (int)i; }
    }
    fc.h = O51::mul(w, B.load(bi));
    std::vector<int> c = B.path(bi);
    word.insert(word.end(), c.begin(), c.end());
    fc.word = word;
    fc.dist = orbit_distance(fc.h, p);
    fc.disp = O51::displacement(fc.h);
    return fc;
}

